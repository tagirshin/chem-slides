import { build } from 'esbuild';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

process.chdir(fileURLToPath(new URL('.', import.meta.url)));

await build({
  absWorkingDir: process.cwd(),
  entryPoints: ['./vendor-entry.mjs'],
  outfile: '../skills/chem-slides/scripts/vendor.mjs',
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'esm',
  minify: true,
  legalComments: 'eof',
  banner: { js: '// Generated by build/rebuild.mjs. See third-party-licenses.txt.' },
});

const lock = JSON.parse(await readFile('package-lock.json', 'utf8'));
const notices = [];
for (const [directory, entry] of Object.entries(lock.packages)) {
  if (!directory || directory.includes('esbuild')) continue;
  const files = await readdir(directory);
  const name = directory.split('node_modules/').at(-1);
  const license = files.find(name => /^(licen[cs]e|copying)(\..+)?$/i.test(name));
  if (!license && name === 'boolbase') {
    notices.push('boolbase 1.0.0 (ISC)\n\nAuthor: Felix Boehm. The package declares ISC in its manifest and ships no separate license file.\nhttps://github.com/fb55/boolbase');
    continue;
  }
  if (!license) throw new Error(`Missing license in ${directory}`);
  notices.push(`${name} ${entry.version} (${entry.license})\n\n${(await readFile(`${directory}/${license}`, 'utf8')).trim()}`);
}
await writeFile('../skills/chem-slides/scripts/third-party-licenses.txt', notices.join('\n\n========\n\n') + '\n');
